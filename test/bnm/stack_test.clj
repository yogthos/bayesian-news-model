(defn- close? [a b tol] (< (Math/abs (- (double a) (double b))) tol))

(deftest the-fit-matches-the-study
  (let [{:keys [a b]} (s/fit (:e fixture) (:y fixture) (:off fixture))]
    (is (close? a (:a fixture) 1e-8))
    (is (every? true? (map #(close? %1 %2 1e-8) b (:b fixture))))
    (is (= 0.0 (nth b 2)) "a weight the data push negative is pinned to 0")))

(deftest weights-are-never-negative
  (let [e (vec (for [i (range 400)] (let [g (Math/sin i)] [g (- g)])))
        y (mapv (fn [[g _]] (if (> g 0.3) 1.0 0.0)) e)
        {:keys [b]} (s/fit e y (vec (repeat 400 0.0)))]
    (is (pos? (first b)))
    (is (= 0.0 (second b)))))

(deftest the-mean-offset-is-the-mixtures-and-clipped-as-the-study
  (is (close? (s/mean-offset [[0.5 -1.0] [0.5 2.0]]) 0.3017458536319332 1e-12))
  (is (close? (s/mean-offset [[1.0 -20.0]]) -13.815509557963773 1e-9)))

(deftest a-forecast-is-integrated-over-the-offsets
  (is (close? (s/forecast {:a 0.5 :b [1.0 2.0]} [0.1 -0.2] [[0.25 -1.0] [0.75 1.0]])
              (+ (* 0.25 (/ 1 (+ 1 (Math/exp (- (+ -1.0 0.5 0.1 -0.4))))))
                 (* 0.75 (/ 1 (+ 1 (Math/exp (- (+ 1.0 0.5 0.1 -0.4)))))))
              1e-12)))

(deftest deviations-read-only-live-groups
  (is (= [0.5 0.0 0.0]
         (s/deviations [:a :b :c] {:a 1.5 :b 2.0 :c Double/NaN} {:a 0.4 :b 0.0 :c 0.6} 1.0))))

(deftest the-fit-reads-only-rows-known-by-the-origin
  (let [row (fn [origin known y] {:e [(if (pos? y) 1.0 -1.0)] :off -2.0 :y y :origin origin :known-at known})
        rows (concat (for [i (range 10)] (row (+ (* 12 1990) 11) (+ (* 12 1991) 11) (if (< i 5) 1.0 0.0)))
                     (for [i (range 10)] (row (+ (* 12 1995) 11) (+ (* 12 1996) 11) 1.0)))]
    (testing "fewer than five onsets known: nothing"
      (is (nil? (s/fit-at (take 4 rows) (+ (* 12 1991) 11))))
      (is (some? (s/fit-at (take 10 rows) (+ (* 12 1991) 11))) "five is enough"))
    (testing "the later rows are not read before they are known"
      (is (= (s/fit-at rows (+ (* 12 1991) 11)) (s/fit-at (take 10 rows) (+ (* 12 1991) 11)))))
    (testing "rows before 1975 are not read"
      (is (nil? (s/fit-at (map #(assoc % :origin 100) (take 10 rows)) (+ (* 12 1991) 11)))))))

